"""
Backend configuration shared by the Gaussian and ORCA external interfaces.

An :class:`ExternalCalculator` describes the level of theory evaluated
outside the host program (an ML potential, xTB, or any ASE calculator)
and writes the small launcher script the host program executes for each
energy/gradient request. Host subclasses
(:class:`chemsmart.jobs.gaussian.external.GaussianExternalCalculator`,
:class:`chemsmart.jobs.orca.external.ORCAExternalCalculator`) choose the
runtime module the launcher calls and how the launcher is referenced in
the host's input file.
"""

import hashlib
import json
import logging
import os
import stat
import sys

from chemsmart.io.external import validate_backend

logger = logging.getLogger(__name__)

_LAUNCHER_TEMPLATE = '''\
#!{python}
"""{host} external launcher generated by chemsmart (backend: {backend}).

{host} calls this script for every energy/gradient request.
"""
import sys

from {runtime_module} import main

CONFIG = {config!r}

if __name__ == "__main__":
    sys.exit(main(CONFIG))
'''


class ExternalCalculator:
    """
    External level of theory for a host quantum-chemistry program.

    Args:
        backend (str): A registered backend
            (:func:`chemsmart.io.external.available_backends`). Built in:
            ``ase`` takes any ASE calculator via ``calculator``;
            ``mace-off``, ``mace-mp``, ``aimnet2`` and ``uma`` are
            machine-learning-potential presets; ``xtb`` runs the xtb binary.
        calculator (str, optional): Dotted import path of an ASE
            calculator class or factory (required for ``backend="ase"``).
        options (dict, optional): Backend keyword options, e.g.
            ``{"model": "medium", "device": "cuda"}`` for MACE or
            ``{"method": "gfn2", "alpb": "water"}`` for xtb.
        python_executable (str, optional): Interpreter that runs the
            launcher; defaults to the interpreter running chemsmart when
            the input is written.
        keep_backend_output (bool): Keep the backend program's working
            files for every request in
            ``<label>_external/step_<NNNN>_<time>/``, next to the per-job
            log ``<label>_external.log`` (which always records one line
            per request).

    Subclasses set :attr:`host`, :attr:`runtime_module` (the module whose
    ``main(config)`` the launcher calls) and :attr:`script_prefix`, and
    may add fields through :meth:`_extra_fields`.
    """

    host = None
    runtime_module = None
    script_prefix = None

    def __init__(
        self,
        backend,
        calculator=None,
        options=None,
        python_executable=None,
        keep_backend_output=False,
    ):
        # raises ValueError for unknown backends and bad options now,
        # not later inside the host program's run
        self.backend = validate_backend(backend, options, calculator).name
        self.calculator = calculator
        self.options = dict(options or {})
        self.python_executable = python_executable
        self.keep_backend_output = bool(keep_backend_output)

    def _extra_fields(self):
        """Host-specific fields, included in :meth:`to_dict` and
        :attr:`config`."""
        return {}

    @classmethod
    def from_dict(cls, data):
        """Build from a mapping, e.g. an ``external:`` block in YAML."""
        return cls(**data)

    def to_dict(self):
        return {
            "backend": self.backend,
            "calculator": self.calculator,
            "options": dict(self.options),
            **self._extra_fields(),
            "keep_backend_output": self.keep_backend_output,
            "python_executable": self.python_executable,
        }

    def __eq__(self, other):
        if type(self) is not type(other):
            return NotImplemented
        return self.to_dict() == other.to_dict()

    def __repr__(self):
        return f"{type(self).__name__}({self.to_dict()!r})"

    @property
    def config(self):
        """Launcher configuration (everything the runtime side needs)."""
        return {
            "backend": self.backend,
            "calculator": self.calculator,
            "options": dict(self.options),
            **self._extra_fields(),
            "keep_backend_output": self.keep_backend_output,
        }

    @property
    def script_filename(self):
        """Launcher name, unique per host and configuration.

        The launcher does not depend on the molecule (charge and
        multiplicity come from the host program at run time), so jobs
        sharing a folder and a configuration share one launcher.
        """
        digest = hashlib.sha1(
            json.dumps(self.config, sort_keys=True, default=str).encode()
        ).hexdigest()[:8]
        backend = self.backend.replace("-", "_")
        return f"{self.script_prefix}_{backend}_{digest}.py"

    @property
    def python(self):
        return self.python_executable or sys.executable

    def _runtime_config(self, server=None):
        """Config written into the launcher, with server defaults resolved.

        For xtb without an explicit ``executable`` option, the xtb path
        from the server YAML is used when available. This does not change
        :attr:`script_filename`, which depends only on :attr:`config`.
        """
        config = self.config
        if (
            self.backend == "xtb"
            and "executable" not in config["options"]
            and server is not None
        ):
            from chemsmart.settings.executable import XTBExecutable

            try:
                executable = XTBExecutable.from_servername(server.name)
            except Exception as exc:
                logger.debug(f"No xtb executable from server config: {exc}")
            else:
                config["options"]["executable"] = executable.get_executable()
        return config

    @staticmethod
    def log_filename(label):
        """Per-job external log name; starts with ``label`` so it is
        copied back from scratch with the job's other files."""
        return f"{label}_external.log"

    @classmethod
    def output_folder_name(cls, label):
        """Folder of kept backend outputs (``keep_backend_output``):
        the log name without ``.log``, e.g. ``<label>_external``. The
        launcher derives it from the log path the same way
        (:attr:`chemsmart.io.external.runlog.ExternalRunLog.backend_output_folder`).
        """
        return os.path.splitext(cls.log_filename(label))[0]

    def write_script(self, directory, server=None):
        """Write the executable launcher into ``directory``; return path."""
        os.makedirs(directory, exist_ok=True)
        path = os.path.join(directory, self.script_filename)
        content = _LAUNCHER_TEMPLATE.format(
            python=self.python,
            host=self.host,
            backend=self.backend,
            runtime_module=self.runtime_module,
            config=self._runtime_config(server),
        )
        with open(path, "w") as fh:
            fh.write(content)
        mode = os.stat(path).st_mode
        os.chmod(path, mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        logger.info(f"Wrote {self.host} external launcher: {path}")
        return os.path.abspath(path)
