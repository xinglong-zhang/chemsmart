"""
Run Gaussian optimisers (opt, TS, modred, scan, IRC, ...) on an external
level of theory: machine-learning potentials, xTB, or any ASE calculator.

:class:`GaussianExternalCalculator` is set as the ``external`` attribute
of :class:`~chemsmart.jobs.gaussian.settings.GaussianJobSettings`. When
present, it replaces the QM method in the route with
``External="<python> <launcher>"``, and the Gaussian job runner writes the
launcher script next to the ``.com`` file. The launcher hands each
request to :func:`chemsmart.io.gaussian.external.main`.
"""

import hashlib
import json
import logging
import os
import stat
import sys

from chemsmart.io.gaussian.external import DEFAULT_FD_STEP, HESSIAN_MODES

logger = logging.getLogger(__name__)

EXTERNAL_BACKENDS = ("ase", "mace-off", "mace-mp", "aimnet2", "uma", "xtb")

_LAUNCHER_TEMPLATE = '''\
#!{python}
"""Gaussian External launcher generated by chemsmart (backend: {backend}).

Gaussian calls this script for every energy/gradient/Hessian request.
"""
import sys

from chemsmart.io.gaussian.external import main

CONFIG = {config!r}

if __name__ == "__main__":
    sys.exit(main(CONFIG))
'''


class GaussianExternalCalculator:
    """
    Backend configuration for Gaussian's ``External=`` keyword.

    Args:
        backend (str): One of :data:`EXTERNAL_BACKENDS`.
            ``ase`` takes any ASE calculator via ``calculator``;
            ``mace-off``, ``mace-mp``, ``aimnet2`` and ``uma`` are
            machine-learning-potential presets; ``xtb`` runs the xtb binary.
        calculator (str, optional): Dotted import path of an ASE
            calculator class or factory (required for ``backend="ase"``).
        options (dict, optional): Backend keyword options, e.g.
            ``{"model": "medium", "device": "cuda"}`` for MACE or
            ``{"method": "gfn2", "alpb": "water"}`` for xtb.
        hessian (str): ``auto`` (engine Hessian if available and
            consistent, else finite differences), ``analytic`` or ``fd``.
        fd_step (float): Finite-difference displacement in Angstrom.
        python_executable (str, optional): Interpreter Gaussian uses to
            run the launcher; defaults to the interpreter running
            chemsmart when the input is written.
    """

    def __init__(
        self,
        backend,
        calculator=None,
        options=None,
        hessian="auto",
        fd_step=DEFAULT_FD_STEP,
        python_executable=None,
    ):
        backend = str(backend).lower()
        if backend not in EXTERNAL_BACKENDS:
            raise ValueError(
                f"Unknown External backend {backend!r}; choose from "
                f"{', '.join(EXTERNAL_BACKENDS)}."
            )
        if backend == "ase" and not calculator:
            raise ValueError(
                "backend 'ase' needs a calculator dotted path, e.g. "
                "'ase.calculators.emt.EMT'."
            )
        if hessian not in HESSIAN_MODES:
            raise ValueError(
                f"hessian must be one of {', '.join(HESSIAN_MODES)}."
            )
        if fd_step <= 0:
            raise ValueError("fd_step must be positive.")
        self.backend = backend
        self.calculator = calculator
        self.options = dict(options or {})
        self.hessian = hessian
        self.fd_step = float(fd_step)
        self.python_executable = python_executable

    @classmethod
    def from_dict(cls, data):
        """Build from a mapping, e.g. an ``external:`` block in YAML."""
        return cls(**data)

    def to_dict(self):
        return {
            "backend": self.backend,
            "calculator": self.calculator,
            "options": dict(self.options),
            "hessian": self.hessian,
            "fd_step": self.fd_step,
            "python_executable": self.python_executable,
        }

    def __eq__(self, other):
        if not isinstance(other, GaussianExternalCalculator):
            return NotImplemented
        return self.to_dict() == other.to_dict()

    def __repr__(self):
        return f"{type(self).__name__}({self.to_dict()!r})"

    @property
    def config(self):
        """Launcher configuration (everything the runtime side needs)."""
        return {
            "backend": self.backend,
            "calculator": self.calculator,
            "options": dict(self.options),
            "hessian": self.hessian,
            "fd_step": self.fd_step,
        }

    @property
    def script_filename(self):
        """Launcher name, unique per configuration.

        The launcher does not depend on the molecule (charge and
        multiplicity come from Gaussian at run time), so jobs sharing a
        folder and a configuration share one launcher.
        """
        digest = hashlib.sha1(
            json.dumps(self.config, sort_keys=True, default=str).encode()
        ).hexdigest()[:8]
        backend = self.backend.replace("-", "_")
        return f"chemsmart_external_{backend}_{digest}.py"

    @property
    def python(self):
        return self.python_executable or sys.executable

    @property
    def route_value(self):
        """Value for ``External=`` in the route, always quoted."""
        return f'"{self.python} {self.script_filename}"'

    def _runtime_config(self, server=None):
        """Config written into the launcher, with server defaults resolved.

        For xtb without an explicit ``executable`` option, the xtb path
        from the server YAML is used when available. This does not change
        :attr:`script_filename`, which depends only on :attr:`config`.
        """
        config = self.config
        if (
            self.backend == "xtb"
            and "executable" not in config["options"]
            and server is not None
        ):
            from chemsmart.settings.executable import XTBExecutable

            try:
                executable = XTBExecutable.from_servername(server.name)
            except Exception as exc:
                logger.debug(f"No xtb executable from server config: {exc}")
            else:
                config["options"]["executable"] = executable.get_executable()
        return config

    def write_script(self, directory, server=None):
        """Write the executable launcher into ``directory``; return path."""
        os.makedirs(directory, exist_ok=True)
        path = os.path.join(directory, self.script_filename)
        content = _LAUNCHER_TEMPLATE.format(
            python=self.python,
            backend=self.backend,
            config=self._runtime_config(server),
        )
        with open(path, "w") as fh:
            fh.write(content)
        mode = os.stat(path).st_mode
        os.chmod(path, mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        logger.info(f"Wrote Gaussian External launcher: {path}")
        return os.path.abspath(path)
